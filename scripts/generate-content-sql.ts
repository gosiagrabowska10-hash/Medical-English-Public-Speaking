/**
 * Generates the curriculum seed migration from src/content/*.
 *   npx tsx scripts/generate-content-sql.ts
 * The output is idempotent (upserts). After launch, content staff edit the
 * database directly (admin UI in Stage 7); regenerate only for bulk updates.
 */
import { writeFileSync } from "node:fs";
import { modules } from "../src/content/curriculum";
import { lessonSpecs } from "../src/content/lessons";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const j = (v: unknown) => (v == null ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]::text[]`;

const specByCode = new Map(lessonSpecs.map((s) => [s.code, s]));
const out: string[] = [
  "-- Generated by scripts/generate-content-sql.ts — do not edit by hand.",
  "-- Curriculum: 12 modules, 30 lessons, 6 workshops. Idempotent upserts.",
  "",
];

for (const m of modules) {
  out.push(
    `insert into public.modules (number, slug, title, weeks_label, summary, outcomes) values (${m.number}, ${q(m.slug)}, ${q(m.title)}, ${q(m.weeks)}, ${q(m.summary)}, ${arr(m.outcomes)})`,
    `  on conflict (number) do update set slug = excluded.slug, title = excluded.title, weeks_label = excluded.weeks_label, summary = excluded.summary, outcomes = excluded.outcomes;`,
  );
  const items = [
    ...m.lessons.map((l) => ({ code: l.code, title: l.title, summary: l.summary, kind: "lesson" })),
    ...(m.workshop ? [{ code: m.workshop.code, title: m.workshop.title, summary: m.workshop.summary, kind: "workshop" }] : []),
  ];
  items.forEach((it, i) => {
    const s = specByCode.get(it.code);
    if (!s) throw new Error(`No schedule for ${it.code}`);
    const slug = `${it.code.toLowerCase()}-${it.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "")}`;
    out.push(
      `insert into public.lessons (module_id, code, kind, slug, title, summary, duration_minutes, week, position, is_preview, video_status, content_status, ai_teacher)`,
      `  select id, ${q(it.code)}, '${it.kind}', ${q(slug)}, ${q(it.title)}, ${q(it.summary)}, ${s.minutes}, ${s.week}, ${i + 1}, ${!!s.preview}, '${s.video?.status ?? "not_recorded"}', '${s.status}', ${q(s.aiTeacher)} from public.modules where number = ${m.number}`,
      `  on conflict (code) do update set module_id = excluded.module_id, kind = excluded.kind, slug = excluded.slug, title = excluded.title, summary = excluded.summary, duration_minutes = excluded.duration_minutes, week = excluded.week, position = excluded.position, is_preview = excluded.is_preview, video_status = excluded.video_status, content_status = excluded.content_status, ai_teacher = excluded.ai_teacher;`,
    );
    const body = s.body ? { ...s.body, ...("workshop" in s ? { workshop: (s as { workshop: unknown }).workshop } : {}) } : { intro: it.summary, objectives: m.outcomes, sections: [], examples: [], demonstration: "", mistakes: [], reflection: [] };
    out.push(
      `insert into public.lesson_content (lesson_id, body, exercise, assignment, video_url, captions_url, video_note)`,
      `  select id, ${j(body)}, ${j(s.exercise)}, ${j(s.assignment)}, ${q(s.video?.url)}, ${q(s.video?.captions)}, ${q(s.video?.note)} from public.lessons where code = ${q(it.code)}`,
      `  on conflict (lesson_id) do update set body = excluded.body, exercise = excluded.exercise, assignment = excluded.assignment, video_url = excluded.video_url, captions_url = excluded.captions_url, video_note = excluded.video_note;`,
    );
    out.push(`delete from public.quiz_questions where lesson_id = (select id from public.lessons where code = ${q(it.code)});`);
    (s.quiz ?? []).forEach((qq, k) =>
      out.push(
        `insert into public.quiz_questions (lesson_id, position, prompt, options, correct_index, explanation) select id, ${k + 1}, ${q(qq.prompt)}, ${arr(qq.options)}, ${qq.correct}, ${q(qq.explanation)} from public.lessons where code = ${q(it.code)};`,
      ),
    );
    out.push(`delete from public.lesson_resources where lesson_id = (select id from public.lessons where code = ${q(it.code)});`);
    (s.resources ?? []).forEach((r, k) =>
      out.push(
        `insert into public.lesson_resources (lesson_id, position, title, description, file_url, is_sample) select id, ${k + 1}, ${q(r.title)}, ${q(r.description)}, ${q(r.file_url)}, ${r.is_sample} from public.lessons where code = ${q(it.code)};`,
      ),
    );
    out.push("");
  });
}

const file = "supabase/migrations/20261125000003_curriculum_content.sql";
writeFileSync(file, out.join("\n"));
console.log(`Wrote ${file}: ${modules.length} modules, ${lessonSpecs.length} lessons/workshops`);
